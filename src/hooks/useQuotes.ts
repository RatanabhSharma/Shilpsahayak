export function useUpdateQuote() {
  const queryClient = useQueryClient();

  return useMutation({
    mutationFn: async ({
      id,
      ...data
    }: Partial<Quote> & {
      id: string;
    }) => {
      await updateDoc(
        doc(db, 'quotes', id),
        data
      );
    },

    onSuccess: () => {
      queryClient.invalidateQueries({
        queryKey: ['quotes']
      });

      queryClient.invalidateQueries({
        queryKey: ['my-quotes']
      });
    }
  });
}

/* -------------------------------------------------------------------------- */
/* Delete quote                                                               */
/* -------------------------------------------------------------------------- */

export function useDeleteQuote() {
  const queryClient =
    useQueryClient();

  return useMutation({
    mutationFn: async ({
      id,
      fileUrl
    }: {
      id: string;
      fileUrl?: string;
    }) => {
      /*
       * Remove uploaded file first,
       * if this quote has one.
       */
      if (fileUrl) {
        await deleteUploadedFile(
          fileUrl
        );
      }

      /*
       * Then remove the Firestore
       * quote document.
       */
      await deleteDoc(
        doc(db, 'quotes', id)
      );
    },

    onSuccess: () => {
      queryClient.invalidateQueries({
        queryKey: ['quotes']
      });

      queryClient.invalidateQueries({
        queryKey: ['my-quotes']
      });
    }
  });
}/* -------------------------------------------------------------------------- */
/* Customer: Accept / Reject quote                                             */
/* -------------------------------------------------------------------------- */

export function useRespondToQuote() {
  const queryClient = useQueryClient();

  return useMutation({
    mutationFn: async ({
      id,
      status,
    }: {
      id: string;
      status: 'Accepted' | 'Rejected';
    }) => {
      if (!id) {
        throw new Error('Quote ID is required.');
      }

      await updateDoc(
        doc(db, 'quotes', id),
        {
          status,
        }
      );
    },

    onSuccess: (_, variables) => {
      queryClient.invalidateQueries({
        queryKey: ['my-quotes'],
      });

      queryClient.invalidateQueries({
        queryKey: ['quotes'],
      });

      queryClient.invalidateQueries({
        queryKey: ['my-quote', variables.id],
      });
    },
  });
}


